function buildCatalog(overrides: Record<string, string> | undefined): Record<string, string> {
  return overrides ? { ...en, ...overrides } : en;
}

const catalogs: Record<Locale, Record<string, string>> = {
  en,
  it, // already spreads en
  es: buildCatalog(extraCatalogs.es),
  "pt-BR": buildCatalog(extraCatalogs["pt-BR"]),
  fr: buildCatalog(extraCatalogs.fr),
  de: buildCatalog(extraCatalogs.de),
  ko: buildCatalog(extraCatalogs.ko),
  ja: buildCatalog(extraCatalogs.ja),
  zh: buildCatalog(extraCatalogs.zh),
};

export const LOCALE_STORAGE_KEY = "bitcroupier.locale.v1";

export function translate(locale: Locale, key: string, variables: Variables = {}): string {
  const template = catalogs[locale]?.[key] ?? en[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_, name: string) => String(variables[name] ?? `{${name}}`));
}

export function readStoredLocale(): Locale | null {
  if (typeof localStorage === "undefined") return null;
  const value = localStorage.getItem(LOCALE_STORAGE_KEY);
  return isLocale(value) ? value : null;
}

export function storeLocale(locale: Locale): void {
  if (typeof localStorage !== "undefined") localStorage.setItem(LOCALE_STORAGE_KEY, locale);
  if (typeof document !== "undefined") document.documentElement.lang = numberFormatTag(locale);
}
